#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ThreadStatus {
    pub role: ThreadRole,
    pub network_name: Option<String>,
    pub channel: Option<u16>,
    pub pan_id: Option<String>,
    pub extended_pan_id: Option<String>,
    pub mesh_local_prefix: Option<String>,
    pub addresses: Vec<String>,
}

impl ThreadStatus {
    /// Whether the Thread interface currently participates in an attached
    /// network role. A running OTBR can be available while still disabled or
    /// detached.
    #[must_use]
    pub fn is_attached(&self) -> bool {
        self.role.is_attached()
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ThreadRole {
    Disabled,
    Detached,
    Child,
    Router,
    Leader,
    Unknown(String),
}

impl ThreadRole {
    #[must_use]
    pub fn from_otbr(value: String) -> Self {
        match value.as_str() {
            "disabled" => Self::Disabled,
            "detached" => Self::Detached,
            "child" => Self::Child,
            "router" => Self::Router,
            "leader" => Self::Leader,
            _ => Self::Unknown(value),
        }
    }

    #[must_use]
    pub fn as_str(&self) -> &str {
        match self {
            Self::Disabled => "disabled",
            Self::Detached => "detached",
            Self::Child => "child",
            Self::Router => "router",
            Self::Leader => "leader",
            Self::Unknown(value) => value,
        }
    }

    #[must_use]
    pub fn is_attached(&self) -> bool {
        matches!(self, Self::Child | Self::Router | Self::Leader)
    }
}

/// Parameters used to form a completely new Thread network.
///
/// The optional network key is held in zeroizing memory and is redacted from
/// debug output. Omitted identifiers and credentials are generated by
/// OpenThread rather than inherited from the previous operational dataset.
#[derive(Clone)]
pub struct CreateNetwork {
    network_name: String,
    channel: Option<u16>,
    pan_id: Option<String>,
    extended_pan_id: Option<String>,
    network_key: Option<SecretString>,
}

impl CreateNetwork {
    /// Validates and normalizes all caller-controlled network parameters.
    ///
    /// Network names must already be in their canonical form; leading or
    /// trailing whitespace is rejected rather than silently changing the
    /// network that will be created.
    pub fn new(
        network_name: String,
        channel: Option<u16>,
        pan_id: Option<String>,
        extended_pan_id: Option<String>,
        network_key: Option<String>,
    ) -> Result<Self> {
        let normalized =
            normalize_create_network(network_name, channel, pan_id, extended_pan_id, network_key)?;
        Ok(Self {
            network_name: normalized.network_name,
            channel: normalized.channel,
            pan_id: normalized.pan_id,
            extended_pan_id: normalized.extended_pan_id,
            network_key: normalized.network_key.map(SecretString::new),
        })
    }

    pub(crate) fn network_name(&self) -> &str {
        &self.network_name
    }

    pub(crate) fn channel(&self) -> Option<u16> {
        self.channel
    }

    pub(crate) fn pan_id(&self) -> Option<&str> {
        self.pan_id.as_deref()
    }

    pub(crate) fn extended_pan_id(&self) -> Option<&str> {
        self.extended_pan_id.as_deref()
    }

    pub(crate) fn network_key(&self) -> Option<&str> {
        self.network_key
            .as_ref()
            .map(ExposeSecret::expose_secret)
            .map(String::as_str)
    }
}

pub(crate) struct ValidatedCreateNetwork {
    pub(crate) network_name: String,
    pub(crate) channel: Option<u16>,
    pub(crate) pan_id: Option<String>,
    pub(crate) extended_pan_id: Option<String>,
    pub(crate) network_key: Option<String>,
}

impl fmt::Debug for CreateNetwork {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("CreateNetwork")
            .field("network_name", &self.network_name)
            .field("channel", &self.channel)
            .field("pan_id", &self.pan_id)
            .field("extended_pan_id", &self.extended_pan_id)
            .field(
                "network_key",
                &self.network_key.as_ref().map(|_| "[REDACTED]"),
            )
            .finish()
    }
}

/// The active Thread network configuration, including credentials.
///
/// Values are held in zeroizing memory and redacted from debug output. The
/// explicit exposure methods make credential reads visible at call sites.
#[derive(Clone)]
pub struct ThreadActiveDataset {
    active_dataset_tlvs: SecretString,
    network_key: Option<SecretString>,
    pskc: Option<SecretString>,
}

impl ThreadActiveDataset {
    pub(crate) fn new(
        active_dataset_tlvs: String,
        network_key: Option<String>,
        pskc: Option<String>,
    ) -> Self {
        Self {
            active_dataset_tlvs: SecretString::new(active_dataset_tlvs),
            network_key: network_key.map(SecretString::new),
            pskc: pskc.map(SecretString::new),
        }
    }

    #[must_use]
    pub fn expose_active_dataset_tlvs(&self) -> &str {
        self.active_dataset_tlvs.expose_secret()
    }

    #[must_use]
    pub fn expose_network_key(&self) -> Option<&str> {
        self.network_key
            .as_ref()
            .map(ExposeSecret::expose_secret)
            .map(String::as_str)
    }

    #[must_use]
    pub fn expose_pskc(&self) -> Option<&str> {
        self.pskc
            .as_ref()
            .map(ExposeSecret::expose_secret)
            .map(String::as_str)
    }
}

impl fmt::Debug for ThreadActiveDataset {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("ThreadActiveDataset")
            .field("active_dataset_tlvs", &"[REDACTED]")
            .field(
                "network_key",
                &self.network_key.as_ref().map(|_| "[REDACTED]"),
            )
            .field("pskc", &self.pskc.as_ref().map(|_| "[REDACTED]"))
            .finish()
    }
}

