#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ThreadRuntimeSnapshot {
    pub available: bool,
    pub rcp_device: Option<PathBuf>,
    pub message: Option<String>,
    pub phase: ThreadRuntimePhase,
    pub consecutive_failures: u32,
    pub restart_count: u64,
    pub next_retry_at: Option<SystemTime>,
    pub last_exit: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ThreadRuntimePhase {
    Pending,
    WaitingForRcp,
    Starting,
    Ready,
    Degraded,
    Backoff,
    Stopped,
}

impl ThreadRuntimePhase {
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Pending => "pending",
            Self::WaitingForRcp => "waiting_for_rcp",
            Self::Starting => "starting",
            Self::Ready => "ready",
            Self::Degraded => "degraded",
            Self::Backoff => "backoff",
            Self::Stopped => "stopped",
        }
    }
}

impl ThreadRuntimeSnapshot {
    #[must_use]
    pub fn unavailable(message: impl Into<String>) -> Self {
        Self {
            available: false,
            rcp_device: None,
            message: Some(message.into()),
            phase: ThreadRuntimePhase::WaitingForRcp,
            consecutive_failures: 0,
            restart_count: 0,
            next_retry_at: None,
            last_exit: None,
        }
    }

    #[must_use]
    pub fn ready(rcp_device: PathBuf) -> Self {
        Self {
            available: true,
            rcp_device: Some(rcp_device),
            message: None,
            phase: ThreadRuntimePhase::Ready,
            consecutive_failures: 0,
            restart_count: 0,
            next_retry_at: None,
            last_exit: None,
        }
    }
}
